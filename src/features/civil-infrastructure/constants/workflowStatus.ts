export type MbStatus = (typeof MB_STATUS)[keyof typeof MB_STATUS];

/**
 * Execution routing. WorkRegistration normalizes every inbound variant
 * (`'External Agency'`, `'External'`, `'ExternalAgency'`) to `EXTERNAL_AGENCY`
 * on save, so readers must compare against these canonical values only.
 */
export const EXECUTION_ROUTE = {
  INTERNAL: 'Internal',
  EXTERNAL_AGENCY: 'ExternalAgency',
} as const;
export type ExecutionRoute =
  (typeof EXECUTION_ROUTE)[keyof typeof EXECUTION_ROUTE];
